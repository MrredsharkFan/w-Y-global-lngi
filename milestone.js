var milestone_time = []
var milestone_rank = []
var valid_milestones = []

// Map of exact replacements
const replacements = [
    // Tags & Math Symbols
    [/\[/g, "<sup>"],
    [/\]/g, "</sup>"],
    [/\{/g, "<sub>"],
    [/\}/g, "</sub>"],
    [/\*/g, "&middot;"],

    // Greek letters (using \b for word boundary match)
    [/\bphi\b/g, "&phi;"],
    [/\bpsi\b/g, "&psi;"],
    [/\bep\b/g, "&epsilon;"],
    [/\bw\b/g, "&omega;"],
    [/\bz\b/g, "&zeta;"],
    [/\bG\b/g, "&Gamma;"],
    [/\bW\b/g, "&Omega;"],
    [" / ", "<br>"]
];

function formatText(str) {
    if (!str) return str;
    for (const [pattern, replacement] of replacements) {
        str = str.replace(pattern, replacement);
    }
    return str;
}

// Main processing loop with row-skipping on bad input
for (var i = 0; i < milestones.length; i++) {
    var p = search_time(milestones[i][0]);
    
    // Skip entire row if search_time returns bad/falsy input
    if (!p || p[0] === undefined || p[1] === undefined) {
        continue;
    }

    milestones[i][1] = formatText(milestones[i][1]);

    // Store only valid entries
    var validIndex = valid_milestones.length;
    valid_milestones[validIndex] = milestones[i];
    milestone_time[validIndex] = p[0];
    milestone_rank[validIndex] = p[1];
}

// Observer set to pause timer updates when divs scroll off-screen
var visibleMilestones = new Set();

const milestoneObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            visibleMilestones.add(entry.target);
            renderMilestoneBox(entry.target);
        } else {
            visibleMilestones.delete(entry.target);
        }
    });
}, { threshold: 0.01 });

// Helper to render individual milestone box contents
function renderMilestoneBox(element) {
    var M = parseInt(element.dataset.index, 10);
    if (isNaN(M) || !valid_milestones[M]) return;

    var ct = get_time(Date.now() - st);
    var T = Date.now() - get_time_inv(milestone_time[M]) - st;
    var R = milestone_rank[M];

    element.style["background-image"] = `linear-gradient(45deg,${(ct >= milestone_time[M]) ? `rgba(140,255,140,${1 - R * 0.03})` : `rgba(255,140,140,${1 - R * 0.03})`},white)`;
    element.innerHTML = `
    <div style="display: flex; flex-direction: row">
        <div style="flex: 1; font-size: 150%">${valid_milestones[M][0]}</div>
        <div style="flex: 1; text-align: right">
            <span style="font-size: 120%">${valid_milestones[M][1]}</span>
            ${T < 0 ? `<br>in ${formatSeconds(-T / 1000)}` : `<br>${formatSeconds(T / 1000)} ago`}<br>
            ${new Date(get_time_inv(milestone_time[M]) + st).toLocaleString()}
        </div>
    </div><hr>
    ${valid_milestones[M][2]}`;
}

// Immediately instantiates ALL divs on site load (no lazy loading)
function init_milestones() {
    const container = document.getElementById("milestone_container");
    if (!container) return;

    container.innerHTML = `Total milestones: ${milestones.length}<br>`;
    for (var i = 0; i < valid_milestones.length; i++) {
        var box = document.createElement("div");
        box.className = "tmilestone-box";
        box.dataset.index = i;
        
        // Initial render so content is populated immediately
        renderMilestoneBox(box);

        container.appendChild(box);
        milestoneObserver.observe(box);
    }
}

// Update timer values for visible elements
function update_milestones() {
    visibleMilestones.forEach(element => {
        renderMilestoneBox(element);
    });
}

// Initialize all elements eagerly on page load
init_milestones();
setInterval(update_milestones, 10);