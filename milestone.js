function formatText(str) {
    if (!str) return str;
    for (const [pattern, replacement] of replacements) {
        str = str.replace(pattern, replacement);
    }
    return str;
}

var visibleMilestones = new Set();

//in fact, i still idk what's an observer
const milestoneObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            visibleMilestones.add(entry.target);
            renderMilestoneBox(entry.target);
        } else {
            visibleMilestones.delete(entry.target);
        }
    });
}, { threshold: 0.01 });

// Helper to render individual milestone box contents
function renderMilestoneBox(element) {
    var M = parseInt(element.dataset.index, 10);

    var ct = get_time(Date.now() - st);
    var T = Date.now() - get_time_inv(valid_milestones[M][4]) - st;
    var R = valid_milestones[M][3];

    element.style["background-image"] = `linear-gradient(45deg,${(ct >= valid_milestones[M][4]) ? `rgba(140,255,140,${1 - R * 0.03})` : `rgba(255,140,140,${1 - R * 0.03})`},white)`;
    //element.style.backgroundColor = (ct >= valid_milestones[M][4]) ? `rgba(140,255,140,${1 - R * 0.03})` : `rgba(255,140,140,${1 - R * 0.03})`;
    element.innerHTML = `
<div style="display: flex; flex-direction: row">
    <div class="milestone_sub_box" style="text-align: left; font-size: 150%">
        <span style="font-size: 70%; color: gray;">${M+1}# </span>
        ${valid_milestones[M][0]}
    </div>
    <div class="milestone_sub_box" style="text-align: right">
        <span style="font-size: 120%">${valid_milestones[M][1]}</span>
        ${T < 0 ? `<br>in ${formatSeconds(-T / 1000)}` : `<br>${formatSeconds(T / 1000)} ago`}<br>
        ${new Date(get_time_inv(valid_milestones[M][4]) + st).toLocaleString()}
    </div>
</div><hr>
${valid_milestones[M][2]}`;
}

// Immediately instantiates ALL divs on site load (no lazy loading)
function init_milestones() {
    const container = document.getElementById("milestone_container");
    if (!container) return;

    document.getElementById("milestone_length").innerHTML = valid_milestones.length
    container.innerHTML = ``;
    for (var i = 0; i < valid_milestones.length; i++) {
        var box = document.createElement("div");
        box.className = "tmilestone-box";
        box.dataset.index = i;


        // Initial render so content is populated immediately
        renderMilestoneBox(box);

        container.appendChild(box);
        milestoneObserver.observe(box);
    }
}

// Update timer values for visible elements
function update_milestones() {
    visibleMilestones.forEach(element => {
        renderMilestoneBox(element);
    });

    var N = 0
    var ct = get_time(Date.now() - st);
    while (valid_milestones[N][4] < ct) {
        N = N+1
    }
    var T = Date.now() - get_time_inv(valid_milestones[N][4]) - st;
    document.getElementById("real_milestone_next").innerHTML = `${N}# ${valid_milestones[N][0]} / ${valid_milestones[N][1]}<br>in ${formatSeconds(-T / 1000)}`
}

// Initialize all elements eagerly on page load
